INSTALL_MD_TEMPLATE = dedent("""\
    # Install Guide: {component_name}

    ## Prerequisites
    - Kubernetes cluster >= {k8s_version_min}
    - Helm >= 3.x installed
    - kubectl configured and connected
    - Sufficient cluster resources (see values.yaml for requirements)

    ## Steps

    ### 1. Create Namespace
    ```bash
    kubectl create namespace {namespace} --dry-run=client -o yaml | kubectl apply -f -
    ```

    ### 2. Add Helm Repository
    ```bash
    {helm_repo_add}
    helm repo update
    ```

    ### 3. Review Configuration
    Review `values.yaml` and adjust for your environment:
    - Resource requests/limits
    - Storage class
    - Node selectors / tolerations
    - Ingress configuration

    ### 4. Install
    ```bash
    bash install.sh
    ```

    ### 5. Validate
    ```bash
    bash validate.sh
    ```

    ### 6. If Something Goes Wrong
    ```bash
    bash rollback.sh
    ```

    ## Post-Install
    {post_install_notes}
""")

INSTALL_SH_TEMPLATE = dedent("""\
    #!/usr/bin/env bash
    # Install script for {component_name}
    # Generated by K8s/Helm Support Copilot
    #
    # Usage: bash install.sh
    # Requires: helm 3.x, kubectl

    set -euo pipefail

    NAMESPACE="{namespace}"
    RELEASE_NAME="{release_name}"
    CHART="{chart_ref}"
    VALUES_FILE="$(dirname "$0")/values.yaml"

    echo "=== Installing {component_name} ==="
    echo "Namespace: $NAMESPACE"
    echo "Release:   $RELEASE_NAME"
    echo ""

    # Step 1: Ensure namespace exists
    echo "[1/4] Creating namespace..."
    kubectl create namespace "$NAMESPACE" --dry-run=client -o yaml | kubectl apply -f -

    # Step 2: Add Helm repo
    echo "[2/4] Adding Helm repository..."
    {helm_repo_add}
    helm repo update

    # Step 3: Install/Upgrade
    echo "[3/4] Installing {component_name}..."
    helm upgrade --install "$RELEASE_NAME" "$CHART" \\
      --namespace "$NAMESPACE" \\
      --values "$VALUES_FILE" \\
      --wait \\
      --timeout 5m

    # Step 4: Quick check
    echo "[4/4] Quick validation..."
    kubectl get pods -n "$NAMESPACE" -l app.kubernetes.io/instance="$RELEASE_NAME"

    echo ""
    echo "=== Installation complete ==="
    echo "Run 'bash validate.sh' for full verification."
""")

VALIDATE_SH_TEMPLATE = dedent("""\
    #!/usr/bin/env bash
    # Validation script for {component_name}
    # Generated by K8s/Helm Support Copilot
    #
    # Usage: bash validate.sh

    set -euo pipefail

    NAMESPACE="{namespace}"
    RELEASE_NAME="{release_name}"
    PASS=0
    FAIL=0

    check() {{
      local desc="$1"
      shift
      echo -n "  [$desc] ... "
      if "$@" > /dev/null 2>&1; then
        echo "PASS"
        ((PASS++))
      else
        echo "FAIL"
        ((FAIL++))
      fi
    }}

    echo "=== Validating {component_name} ==="
    echo ""

    echo "--- Helm Release ---"
    check "Release exists" helm status "$RELEASE_NAME" -n "$NAMESPACE"

    echo ""
    echo "--- Pods ---"
    check "Pods running" kubectl wait --for=condition=Ready pod \\
      -l app.kubernetes.io/instance="$RELEASE_NAME" \\
      -n "$NAMESPACE" --timeout=120s

    echo ""
    echo "--- Services ---"
    check "Service exists" kubectl get svc -n "$NAMESPACE" \\
      -l app.kubernetes.io/instance="$RELEASE_NAME"

    {extra_checks}

    echo ""
    echo "=== Results: $PASS passed, $FAIL failed ==="
    if [ "$FAIL" -gt 0 ]; then
      echo "Some checks failed. Review the output above."
      exit 1
    fi
""")

ROLLBACK_SH_TEMPLATE = dedent("""\
    #!/usr/bin/env bash
    # Rollback script for {component_name}
    # Generated by K8s/Helm Support Copilot
    #
    # Usage: bash rollback.sh [--delete]
    #   --delete  Completely remove the release (default: rollback to previous)

    set -euo pipefail

    NAMESPACE="{namespace}"
    RELEASE_NAME="{release_name}"

    echo "=== Rollback: {component_name} ==="

    if [ "${{1:-}}" = "--delete" ]; then
      echo "Mode: FULL DELETE"
      echo ""
      echo "This will remove the Helm release and all its resources."
      read -p "Are you sure? (yes/no): " confirm
      if [ "$confirm" != "yes" ]; then
        echo "Aborted."
        exit 0
      fi

      echo "[1/2] Uninstalling Helm release..."
      helm uninstall "$RELEASE_NAME" -n "$NAMESPACE"

      echo "[2/2] Cleaning up namespace (optional)..."
      echo "  To delete namespace: kubectl delete namespace $NAMESPACE"

    else
      echo "Mode: ROLLBACK TO PREVIOUS REVISION"
      echo ""

      echo "Current release info:"
      helm history "$RELEASE_NAME" -n "$NAMESPACE" --max 5

      echo ""
      echo "[1/1] Rolling back..."
      helm rollback "$RELEASE_NAME" -n "$NAMESPACE" --wait --timeout 5m

      echo ""
      echo "Post-rollback status:"
      helm status "$RELEASE_NAME" -n "$NAMESPACE"
    fi

    echo ""
    echo "=== Rollback complete ==="
    echo "Run 'bash validate.sh' to verify."
""")

