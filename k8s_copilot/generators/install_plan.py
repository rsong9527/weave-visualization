def generate_install_plan(
    component_name: str,
    namespace: str = "default",
    llm_values_yaml: str | None = None,
    llm_extra_notes: str | None = None,
) -> InstallPlan:
    """Generate a complete install plan for a K8s component.

    Uses known component configurations when available,
    falls back to generic templates otherwise.

    Args:
        component_name: The component to install.
        namespace: Target namespace.
        llm_values_yaml: LLM-generated values.yaml content (overrides template).
        llm_extra_notes: Additional notes from the LLM.

    Returns:
        Complete InstallPlan with all 5 files.
    """
    # Look up known component, or use defaults
    config = KNOWN_COMPONENTS.get(component_name, {})

    chart_ref = config.get("chart_ref", f"{component_name}/{component_name}")
    helm_repo_add = config.get(
        "helm_repo_add",
        f"helm repo add {component_name} https://charts.example.com/{component_name}"
    )
    release_name = config.get("release_name", component_name)
    image_repo = config.get("image_repo", f"docker.io/library/{component_name}")
    image_tag = config.get("image_tag", "latest")
    k8s_version_min = config.get("k8s_version_min", "v1.25")
    post_install_notes = config.get("post_install_notes", "Verify the deployment is healthy.")
    extra_checks = config.get("extra_checks", "")

    if llm_extra_notes:
        post_install_notes += f"\n\n{llm_extra_notes}"

    fmt = dict(
        component_name=component_name,
        namespace=namespace,
        release_name=release_name,
        chart_ref=chart_ref,
        helm_repo_add=helm_repo_add,
        image_repo=image_repo,
        image_tag=image_tag,
        k8s_version_min=k8s_version_min,
        post_install_notes=post_install_notes,
        extra_checks=extra_checks,
    )

    plan = InstallPlan(
        component_name=component_name,
        namespace=namespace,
        install_md=INSTALL_MD_TEMPLATE.format(**fmt),
        install_sh=INSTALL_SH_TEMPLATE.format(**fmt),
        values_yaml=llm_values_yaml or DEFAULT_VALUES_YAML.format(**fmt),
        validate_sh=VALIDATE_SH_TEMPLATE.format(**fmt),
        rollback_sh=ROLLBACK_SH_TEMPLATE.format(**fmt),
    )

    return plan
