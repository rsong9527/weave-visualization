"""
Install Plan Generator

Produces the 5-file install pack:
  - install.md  (human-readable steps)
  - install.sh  (executable script)
  - values.yaml (configuration)
  - validate.sh (post-install verification)
  - rollback.sh (undo script)

The model generates content for these files; this module provides
the templates and structure.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path
from textwrap import dedent


@dataclass
class InstallPlan:
    """A complete install plan with all 5 required files."""

    component_name: str
    namespace: str = "default"
    install_md: str = ""
    install_sh: str = ""
    values_yaml: str = ""
    validate_sh: str = ""
    rollback_sh: str = ""

    def save(self, output_dir: str | Path) -> Path:
        """Save all install plan files to a directory.

        Args:
            output_dir: Directory to save files in (created if needed).

        Returns:
            Path to the output directory.
        """
        out = Path(output_dir) / f"install-{self.component_name}"
        out.mkdir(parents=True, exist_ok=True)

        files = {
            "install.md": self.install_md,
            "install.sh": self.install_sh,
            "values.yaml": self.values_yaml,
            "validate.sh": self.validate_sh,
            "rollback.sh": self.rollback_sh,
        }

        for filename, content in files.items():
            filepath = out / filename
            filepath.write_text(content, encoding="utf-8")
            # Make .sh files executable
            if filename.endswith(".sh"):
                filepath.chmod(filepath.stat().st_mode | 0o755)

        return out

    def to_markdown(self) -> str:
        """Render the full install plan as a single Markdown document."""
        sections = [
            f"# Install Plan: {self.component_name}\n",
            f"**Namespace**: `{self.namespace}`\n",
            "---\n",
            "## install.md\n",
            self.install_md or "_Not generated yet._",
            "\n---\n",
            "## install.sh\n",
            f"```bash\n{self.install_sh}\n```" if self.install_sh else "_Not generated yet._",
            "\n---\n",
            "## values.yaml\n",
            f"```yaml\n{self.values_yaml}\n```" if self.values_yaml else "_Not generated yet._",
            "\n---\n",
            "## validate.sh\n",
            f"```bash\n{self.validate_sh}\n```" if self.validate_sh else "_Not generated yet._",
            "\n---\n",
            "## rollback.sh\n",
            f"```bash\n{self.rollback_sh}\n```" if self.rollback_sh else "_Not generated yet._",
        ]
        return "\n".join(sections)


